#!/usr/bin/env python3
"""Import edited sourceImages full textures back to cocos native assets."""

from __future__ import annotations

import argparse
import io
import shutil
from pathlib import Path
from typing import Any, Dict, List, Tuple

from PIL import Image

from cocos_image_utils import (
    encode_netease_bytes,
    load_json,
    sanitize_rel_component,
    sha256_file,
)


def _arg() -> argparse.Namespace:
    p = argparse.ArgumentParser(description="Import edited sourceImages back to cocos assets.")
    p.add_argument(
        "--project",
        default="/Users/jiaojian/Documents/localweb/doomsdayroom_web-mobile1",
        help="Cocos web build root.",
    )
    p.add_argument(
        "--source",
        default="/Users/jiaojian/Documents/localweb/sourceImages",
        help="sourceImages root generated by export script.",
    )
    p.add_argument(
        "--dry-run",
        action="store_true",
        help="Only print what would be written.",
    )
    p.add_argument(
        "--all",
        action="store_true",
        help="Write all textures from manifest, not only changed ones.",
    )
    p.add_argument(
        "--backup-dir",
        default="",
        help="Optional backup directory (relative to project or absolute).",
    )
    return p.parse_args()


def _image_to_bytes(image: Image.Image, ext: str) -> bytes:
    ext = ext.lower()
    buf = io.BytesIO()
    if ext in (".jpg", ".jpeg"):
        image.convert("RGB").save(buf, format="JPEG", quality=95)
    elif ext == ".webp":
        image.save(buf, format="WEBP", quality=95)
    else:
        image.save(buf, format="PNG")
    return buf.getvalue()


def _has_changes(texture_entry: Dict[str, Any], source_root: Path) -> bool:
    decoded_path = source_root / texture_entry["decodedPath"]
    if not decoded_path.exists():
        return False
    if texture_entry.get("decodedHash") and sha256_file(decoded_path) != texture_entry["decodedHash"]:
        return True
    return False


def _resolve_backup_dir(project_root: Path, raw: str) -> Path:
    candidate = Path(raw)
    if candidate.is_absolute():
        return candidate
    return (project_root / candidate).resolve()


def main() -> int:
    args = _arg()
    project_root = Path(args.project).resolve()
    source_root = Path(args.source).resolve()
    manifest_path = source_root / "manifest.json"
    if not manifest_path.exists():
        raise FileNotFoundError(f"manifest not found: {manifest_path}")

    manifest = load_json(manifest_path)
    textures: List[Dict[str, Any]] = manifest.get("textures", [])
    if not textures:
        print("[import] no textures in manifest")
        return 0

    backup_dir = None
    if args.backup_dir:
        backup_dir = _resolve_backup_dir(project_root, args.backup_dir)
        if not args.dry_run:
            backup_dir.mkdir(parents=True, exist_ok=True)

    to_write: List[Tuple[Dict[str, Any], bytes]] = []
    skipped_unchanged = 0
    skipped_missing = 0
    errors = 0

    for texture in textures:
        native_rel = texture.get("nativePath")
        decoded_rel = texture.get("decodedPath")
        ext = texture.get("ext", ".png")
        if not native_rel or not decoded_rel:
            skipped_missing += 1
            continue

        native_path = project_root / native_rel
        decoded_path = source_root / decoded_rel
        if not native_path.exists() or not decoded_path.exists():
            skipped_missing += 1
            continue

        if not args.all and not _has_changes(texture, source_root):
            skipped_unchanged += 1
            continue

        try:
            merged = Image.open(decoded_path).convert("RGBA")

            expected_size = (int(texture.get("width", 0)), int(texture.get("height", 0)))
            if expected_size[0] > 0 and expected_size[1] > 0 and merged.size != expected_size:
                raise ValueError(
                    f"Texture size mismatch: {decoded_rel} got {merged.size}, expected {expected_size}"
                )

            decoded_bytes = _image_to_bytes(merged, ext)
            final_bytes = encode_netease_bytes(decoded_bytes) if texture.get("encoded") else decoded_bytes
            to_write.append((texture, final_bytes))
        except Exception as exc:
            errors += 1
            print(f"[import][error] {texture.get('bundle')}::{texture.get('logicalPath')} -> {exc}")

    print(f"[import] candidates: {len(to_write)}")
    print(f"[import] skipped unchanged: {skipped_unchanged}")
    print(f"[import] skipped missing: {skipped_missing}")
    print(f"[import] parse errors: {errors}")

    if args.dry_run:
        for texture, _ in to_write[:50]:
            print(
                f"[dry-run] would write {texture.get('nativePath')} "
                f"(bundle={texture.get('bundle')})"
            )
        if len(to_write) > 50:
            print(f"[dry-run] ... and {len(to_write) - 50} more")
        return 0 if errors == 0 else 2

    wrote = 0
    for texture, data in to_write:
        native_rel = texture["nativePath"]
        native_path = project_root / native_rel
        if backup_dir:
            backup_path = backup_dir / sanitize_rel_component(native_rel)
            backup_path.parent.mkdir(parents=True, exist_ok=True)
            if not backup_path.exists():
                shutil.copy2(native_path, backup_path)
        native_path.write_bytes(data)
        wrote += 1

    print(f"[import] wrote textures: {wrote}")
    if backup_dir:
        print(f"[import] backup dir: {backup_dir}")
    return 0 if errors == 0 else 2


if __name__ == "__main__":
    raise SystemExit(main())
